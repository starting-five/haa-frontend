const TABS: { id: Tab; label: string }[] = [
  { id: "home", label: "Home" },
  { id: "cases", label: "Cases" },
  { id: "leads", label: "Leads" },
  { id: "settings", label: "Settings" },
];

export default function AttorneyDashboardPage() {
  // const params = useParams();
  const [activeTab, setActiveTab] = useState<Tab>("home");
  const [firstName, setFirstName] = useState("there");

  useEffect(() => {
    const name = sessionStorage.getItem("onboarding_firstName");
    if (name) setFirstName(name);
  }, []);

  return (
    <div className="min-h-screen bg-white flex flex-col">
      <div className="flex items-center justify-between px-[24px] pt-[68px] py-[12px]">
        <Image
          src="/assets/logo/black-logo.png"
          alt="HelpAfterAccident"
          width={148}
          height={20}
        />
      </div>

      <div className="flex-1 p-[24px] pb-[96px]">
        <h1
          className="text-[28px] font-bold text-[#111] leading-normal"
          style={{ fontFamily: "var(--font-nunito-sans)" }}
        >
          {getGreeting()}, {firstName}.
        </h1>
      </div>

      <div className="fixed bottom-0 left-1/2 -translate-x-1/2 w-full max-w-[393px] bg-white border-t border-[#f0f0f2]">
        <div className="flex items-center px-[16px] py-[10px] h-[64px]">
          {TABS.map(({ id, label }) => {
            const active = activeTab === id;
            return (
              <button
                key={id}
                type="button"
                onClick={() => setActiveTab(id)}
                className="flex flex-1 flex-col items-center justify-center gap-[4px]"
              >
                {id === "home" && <HomeIcon active={active} />}
                {id === "cases" && <CasesIcon active={active} />}
                {id === "leads" && <LeadsIcon active={active} />}
                {id === "settings" && <SettingsIcon active={active} />}
                <span
                  className={`text-[11px] ${active ? "font-semibold text-[#cc007e]" : "font-medium text-[#8e8e93]"}`}
                  style={{ fontFamily: "var(--font-nunito-sans)" }}
                >
                  {label}
                </span>
              </button>
            );
          })}
        </div>
        <div className="flex justify-center pb-[8px]">
          <div className="w-[134px] h-[5px] bg-black opacity-30 rounded-full" />
        </div>
      </div>
    </div>
  );
}
